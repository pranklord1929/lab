grant select on table public.menus to anon, authenticated;
grant select on table public.notes to anon, authenticated;
grant select on table public.faqs to anon, authenticated;
grant select on table public.collections to anon, authenticated;
grant select on table public.collection_restaurants to anon, authenticated;
